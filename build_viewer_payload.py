#!/usr/bin/env python3
"""Embed ml_tts_samples_embedded.parquet into dataset_payload.js for offline viewer."""

from __future__ import annotations

import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PARQUET = ROOT / "ml_tts_samples_embedded.parquet"
OUT = ROOT / "dataset_payload.js"


def main() -> None:
    if not PARQUET.exists():
        raise SystemExit(f"Missing {PARQUET}")

    data = PARQUET.read_bytes()
    b64 = base64.b64encode(data).decode("ascii")

    # Split into lines for safer JS parsing (~76 chars not required for modern engines)
    chunk = 120_000
    parts = [b64[i : i + chunk] for i in range(0, len(b64), chunk)]

    lines = [
        "// Auto-generated by build_viewer_payload.py — do not edit",
        f"// Source: {PARQUET.name} ({len(data)} bytes)",
        "window.EMBEDDED_PARQUET_B64 = [",
    ]
    lines.extend(f'  "{part}",' for part in parts)
    lines.append("].join('');")
    lines.append(f"window.EMBEDDED_PARQUET_NAME = {PARQUET.name!r};")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size / (1024*1024):.1f} MB)")


if __name__ == "__main__":
    main()
